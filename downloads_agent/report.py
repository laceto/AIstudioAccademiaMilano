"""Local HTML report. Everything that comes from a file name or a model is HTML-escaped,
and the page loads nothing from the network."""
from __future__ import annotations

import html
import os
import time
from typing import List

_CSS = """
:root{--bg:#fff;--fg:#1c1c1c;--muted:#666;--line:#ddd;--head:#f3f3f3}
@media (prefers-color-scheme:dark){:root{--bg:#161616;--fg:#e8e8e8;--muted:#9a9a9a;--line:#333;--head:#222}}
body{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;margin:0 auto;max-width:1000px;padding:24px 16px}
h1{font-size:1.4rem;margin:0 0 4px}.meta{color:var(--muted);margin:0 0 20px}
h2{font-size:1.1rem;margin:28px 0 8px}
table{border-collapse:collapse;width:100%}th,td{border-bottom:1px solid var(--line);padding:8px;text-align:left;vertical-align:top}
th{background:var(--head)}td.f{word-break:break-all;width:30%}td.c{white-space:nowrap}
"""


def _e(value) -> str:
    return html.escape(str(value), quote=True)


def render_report(plan: List[dict], skipped: List[dict], model: str) -> str:
    rows = "".join(
        f"<tr><td class='f'>{_e(os.path.basename(i['src']))}</td><td class='c'>{_e(i['category'])}</td>"
        f"<td>{_e(i.get('summary', ''))}</td></tr>"
        for i in plan
    )
    skip_rows = "".join(
        f"<tr><td class='f'>{_e(s['name'])}</td><td>{_e(s['reason'])}</td></tr>" for s in skipped
    )
    now = time.strftime("%Y-%m-%d %H:%M")
    return (
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>"
        "<meta name='viewport' content='width=device-width,initial-scale=1'>"
        f"<title>Downloads summary</title><style>{_CSS}</style></head><body>"
        f"<h1>Downloads summary</h1><p class='meta'>{_e(now)} &middot; {len(plan)} file(s) to move &middot; "
        f"summaries are machine-generated by {_e(model)} on this PC from the start of each file and may be wrong.</p>"
        f"<h2>To move</h2><table><tr><th>File</th><th>Goes to</th><th>About</th></tr>{rows}</table>"
        f"<h2>Left in place</h2><table><tr><th>File</th><th>Why</th></tr>{skip_rows}</table>"
        "</body></html>"
    )
